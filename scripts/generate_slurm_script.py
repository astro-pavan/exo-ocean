"""Generate a CSD3 Slurm batch script that runs one Julia simulation script.

    python scripts/generate_slurm_script.py experiments/tests/base_case_1km.jl 8 ~/rds/clero-env
    sbatch scripts/slurm/base_case_1km.sbatch        (submit from the repo root)
"""
import argparse
import getpass
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
GPU_PARTITIONS = {"ampere"}    # CSD3 A100 nodes; other partitions (e.g. icelake, sapphire) are CPU-only
SL3_MAX_HOURS = 12


def wall_time(hours_or_hms):
    """Slurm time string from hours (e.g. 6.5) or an "HH:MM:SS" string, and the time in hours."""
    if isinstance(hours_or_hms, str) and ":" in hours_or_hms:
        h, m, s = (int(x) for x in hours_or_hms.split(":"))
        return hours_or_hms, h + m / 60 + s / 3600
    hours = float(hours_or_hms)
    minutes = round(hours * 60)
    return f"{minutes // 60:02d}:{minutes % 60:02d}:00", hours


def emulator_python(python_env):
    """Python executable for the CLERO emulator: the env's bin/python, or the path itself if it is already an executable."""
    path = Path(python_env).expanduser()
    return str(path if path.name.startswith("python") else path / "bin" / "python")


def generate_script(script_location, max_wall_time, python_env, node="ampere", email=True, account="SHORTTLE-SL3"):
    """Write scripts/slurm/<script name>.sbatch to run `script_location` (a Julia script, relative to the repo root) and return its path.

    max_wall_time: hours or "HH:MM:SS" (SL3 allows at most 12 h). python_env: the env with `clero`, exported as EXO_EMULATOR_PYTHON for
    emulator winds. node: Slurm partition; "ampere" gets one A100 (and its 32 cores), CPU partitions get one node's cores. email: True
    mails <user>@cam.ac.uk when the job starts, ends or fails, a string mails that address instead, False sends nothing.
    """
    script = Path(script_location)
    if not (REPO_ROOT / script).is_file():
        raise FileNotFoundError(f"{script} not found under {REPO_ROOT}")
    time, hours = wall_time(max_wall_time)
    if hours > SL3_MAX_HOURS and "SL3" in account:
        raise ValueError(f"{time} exceeds the {SL3_MAX_HOURS} h SL3 limit")

    gpu = node in GPU_PARTITIONS
    name = script.stem
    directives = [f"-J {name}", f"-A {account}-{'GPU' if gpu else 'CPU'}", f"-p {node}", "-N1", "-n1", f"--time={time}",
                  "--output=logs/%x-%j.out"]
    directives += ["--gres=gpu:1"] if gpu else ["--exclusive"]
    if email:
        directives += ["--mail-type=BEGIN,END,FAIL", f"--mail-user={email if isinstance(email, str) else getpass.getuser() + '@cam.ac.uk'}"]

    lines = ["#!/bin/bash",
             f"# Runs {script} on CSD3 ({'one A100' if gpu else 'one CPU node'}). Generated by scripts/generate_slurm_script.py.",
             f"#   cd <repo root> && mkdir -p logs && sbatch scripts/slurm/{name}.sbatch",
             *(f"#SBATCH {d}" for d in directives),
             "",
             "set -euo pipefail",
             'cd "$SLURM_SUBMIT_DIR"',
             f'[ -f "{script}" ] || {{ echo "submit from the repo root: {script} not found in $PWD"; exit 1; }}',
             "source env.sh",
             f"export EXO_EMULATOR_PYTHON={emulator_python(python_env)}"]
    if gpu:
        lines += ["export LD_LIBRARY_PATH=$(echo \"${LD_LIBRARY_PATH:-}\" | tr ':' '\\n' | grep -vi cuda | paste -sd: || true)    # CUDA.jl loads its own libraries",
                  'echo "$(date \'+%F %T\')  {} on $(hostname): $(nvidia-smi --query-gpu=name --format=csv,noheader)"'.format(script)]
    else:
        lines += ['echo "$(date \'+%F %T\')  {} on $(hostname) ($(nproc) cores)"'.format(script)]
    lines += [f"julia --project=. -t auto {script}",
              f'echo "$(date \'+%F %T\')  {script} finished"', ""]

    out = REPO_ROOT / "scripts" / "slurm" / f"{name}.sbatch"
    out.parent.mkdir(parents=True, exist_ok=True)
    (REPO_ROOT / "logs").mkdir(exist_ok=True)    # Slurm can't write the job log into a missing directory
    out.write_text("\n".join(lines))
    return out


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("script", help="Julia script, relative to the repo root")
    parser.add_argument("hours", help="wall time in hours or HH:MM:SS")
    parser.add_argument("python_env", help="Python env with clero (for emulator winds)")
    parser.add_argument("--node", default="ampere", help="Slurm partition (default: ampere)")
    parser.add_argument("--no-email", action="store_true", help="don't send job emails")
    parser.add_argument("--account", default="SHORTTLE-SL3", help="project, without the -GPU/-CPU suffix")
    args = parser.parse_args()
    print(generate_script(args.script, args.hours, args.python_env, args.node, not args.no_email, args.account))
